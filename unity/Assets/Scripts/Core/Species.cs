    /// <summary>Падеж названия вида: именительный, винительный, родительный (как G.nm в js/creatures.js).</summary>
    public enum NameCase { Nom, Acc, Gen }

    /// <summary>Заметка для журнала: ключ наблюдения (как в E.emit) и текст.</summary>
    public sealed class SpeciesNote
    {
        public readonly string Key, Text;
        public SpeciesNote(string key, string text) { Key = key; Text = text; }
    }

    /// <summary>
    /// Вид отмели: настоящее имя с падежами (после сканирования) и описательное до сканирования
    /// («мелкая рыба»), описание и заметки для журнала. Gen/UGen могут быть null — тогда берётся
    /// винительный, как `s.gen || s.acc` в браузерной версии.
    /// </summary>
    public sealed class SpeciesInfo
    {
        public readonly string Id, Name, Acc, Gen, UNom, UAcc, UGen, Desc;
        public readonly SpeciesNote[] Notes;

        public SpeciesInfo(string id, string name, string acc, string gen, string unom, string uacc, string ugen,
            string desc, SpeciesNote[] notes)
        {
            Id = id; Name = name; Acc = acc; Gen = gen; UNom = unom; UAcc = uacc; UGen = ugen; Desc = desc; Notes = notes;
        }

        /// <summary>Есть ли у вида заметка с таким ключом.</summary>
        public bool HasNote(string key)
        {
            foreach (var n in Notes) if (n.Key == key) return true;
            return false;
        }

        /// <summary>Название в падеже: настоящее после сканирования, описательное до (G.nm).</summary>
        public string Called(NameCase c, bool scanned)
        {
            if (scanned)
                return c == NameCase.Gen ? Gen ?? Acc : c == NameCase.Acc ? Acc : Name.ToLowerInvariant();
            return c == NameCase.Gen ? UGen ?? UAcc : c == NameCase.Acc ? UAcc : UNom;
        }
    }

