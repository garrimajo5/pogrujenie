        static readonly Dictionary<string, SpeciesInfo> byId = Build();

        static Dictionary<string, SpeciesInfo> Build()
        {
            var d = new Dictionary<string, SpeciesInfo>();
            foreach (var s in All) d.Add(s.Id, s);
            return d;
        }

        public static int Count => All.Length;

        public static bool Has(string id) => id != null && byId.ContainsKey(id);

        public static SpeciesInfo Get(string id)
        {
            if (id == null || !byId.TryGetValue(id, out var s)) throw new ArgumentException("Нет вида: " + id);
            return s;
        }

        /// <summary>Номер вида в порядке журнала, −1 если такого нет.</summary>
        public static int IndexOf(string id)
        {
            for (int i = 0; i < All.Length; i++) if (All[i].Id == id) return i;
            return -1;
        }

        /// <summary>Название вида в падеже (G.nm).</summary>
        public static string Called(string id, NameCase c, bool scanned) => Get(id).Called(c, scanned);

        /// <summary>Первая буква заглавная (G.cap).</summary>
        public static string Cap(string s) => string.IsNullOrEmpty(s) ? s : char.ToUpperInvariant(s[0]) + s.Substring(1);
    }
